"""Build the SDK-only desktop entry. Preview bundling is a separate optional step."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
pieces = (ROOT / "src/pieces.js").read_text().replace("export const PIECES", "const PIECES")
celebration = (ROOT / "src/celebration.js").read_text().replace("export function createCelebration", "function createCelebration")
board = (ROOT / "src/board.js").read_text().replace("import { PIECES } from './pieces.js';", "").replace("import { createCelebration } from './celebration.js';", "").replace("export function createBoard", "function createBoard")
desktop = (ROOT / "src/desktop.js").read_text()
(ROOT / "desktop/plugin.js").write_text("// Generated by scripts/build_ui.py; edit src/ files.\n" + desktop.split("const h =", 1)[0] + pieces + "\n" + celebration + "\n" + board + "\nconst h =" + desktop.split("const h =", 1)[1])
